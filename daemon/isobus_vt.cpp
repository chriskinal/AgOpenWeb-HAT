struct IsobusVt::Impl {
    std::shared_ptr<isobus::InternalControlFunction> tc;
    std::function<void(bool)> setTractorEcu;
    std::vector<std::uint8_t> pool;
    std::shared_ptr<Vt> client;
    std::unique_ptr<isobus::VirtualTerminalClientUpdateHelper> helper;
    std::map<std::uint16_t, std::string> sent;  // the last string sent to each object
    bool started = false, wasConnected = false, configSynced = false, capabilitiesLogged = false;
    bool warned = false, everStarted = false;
    std::uint32_t disconnectedSinceMs = 0, lastStatusMs = 0, lastSectionsMs = 0, lastAppMs = 0;
    std::uint32_t partnerSinceMs = 0;
    std::uint64_t partnerName = 0;
    bool tractorEcuSetting = false;  // what the settings page of the screen shows

    void string(std::uint16_t id, const std::string& value) {
        auto it = sent.find(id);
        if (it != sent.end() && it->second == value) return;
        client->send_change_string_value(id, value);
        sent[id] = value;
    }
    void setup();
    void forget();
    void disconnected();
    void strings(const View& v);
    void sections(const View& v);
};

void IsobusVt::Impl::setup() {
    pool.assign(std::begin(AOG_TC_IOP_DATA), std::end(AOG_TC_IOP_DATA));

    // Any virtual terminal on the bus.
    const isobus::NAMEFilter filter(isobus::NAME::NAMEParameters::FunctionCode,
                                    static_cast<std::uint8_t>(isobus::NAME::Function::VirtualTerminal));
    auto partner = isobus::CANNetworkManager::CANNetwork.create_partnered_control_function(0, {filter});
    client = std::make_shared<Vt>(partner, tc);

    // As upstream: the scaling is part of the version label, so a terminal does not reuse an
    // unscaled copy it stored from another build of the same pool.
    auto versionData = pool;
    const std::string salt = "scaled:" + std::to_string(ISO_MASK_SIZE) + ":" + std::to_string(ISO_DESIGNATOR_HEIGHT) + ":v1";
    versionData.insert(versionData.end(), salt.begin(), salt.end());
    client->set_object_pool(0, pool.data(), static_cast<std::uint32_t>(pool.size()),
                            isobus::IOPFileInterface::hash_object_pool_to_version(versionData));
    client->set_object_pool_scaling(0, ISO_MASK_SIZE, ISO_DESIGNATOR_HEIGHT);

    // The five soft keys change the page.
    client->get_vt_soft_key_event_dispatcher().add_listener([this](const Vt::VTKeyEvent& event) {
        if (event.keyEvent != Vt::KeyActivationCode::ButtonPressedOrLatched) return;
        std::uint16_t mask = 0xFFFF;
        switch (event.objectID) {
        case NavStatus: mask = DataMask_1000; break;
        case NavNetwork: mask = DataMask_Network; break;
        case NavImplement: mask = DataMask_Implement; break;
        case NavDiagnostics: mask = DataMask_Diagnostics; break;
        case NavConfig: mask = DataMask_Config; break;
        default: break;
        }
        if (mask != 0xFFFF) client->send_change_active_mask(WorkingSet_0, mask);
    });

    helper = std::make_unique<isobus::VirtualTerminalClientUpdateHelper>(client);
    helper->add_tracked_numeric_value(VTSpeedValue, 0);
    helper->add_tracked_numeric_value(VTXteValue, 0);
    helper->add_tracked_numeric_value(ConfigTecuEnabled, tractorEcuSetting);

    // The settings page. Only the tractor ECU switch does anything here; it applies at the
    // next start, as the page says.
    client->get_vt_change_numeric_value_event_dispatcher().add_listener([this](const Vt::VTChangeNumericValueEvent& event) {
        if (event.objectID != ConfigTecuEnabled) return;
        const bool on = event.value != 0;
        LOG_NOTICE(Can, "ISOBUS: terminal: tractor ECU role switched %s (applies at the next start)", on ? "on" : "off");
        tractorEcuSetting = on;
        setTractorEcu(on);
    });
    helper->initialize();
}

// The stack ties a partner to the first terminal that matches and keeps it for good, so a
// different terminal (another NAME) that arrives later is never picked up. Start again with a
// fresh partner; the next pass takes whichever terminal is on the bus then.
void IsobusVt::Impl::forget() {
    auto partner = client->get_partner_control_function();
    helper.reset();
    client->terminate();
    client.reset();
    if (partner) isobus::CANNetworkManager::CANNetwork.deactivate_control_function(partner);
    started = false;
}

void IsobusVt::Impl::disconnected() {
    if (wasConnected) {
        LOG_NOTICE(Can, "ISOBUS: terminal: the screen is no longer on the terminal");
        disconnectedSinceMs = SystemTiming::get_timestamp_ms();
        warned = false;
        capabilitiesLogged = false;
    }
    wasConnected = false;
    if (!warned && SystemTiming::time_expired_ms(disconnectedSinceMs, 30000)) {
        LOG_WARNING(Can,
                    "ISOBUS: terminal: a terminal is on the bus but has not taken the screen in 30 s "
                    "(screen %ux%u, soft keys %u virtual / %u physical; the screen needs five)",
                    client->get_number_x_pixels(), client->get_number_y_pixels(), client->get_number_virtual_softkeys(),
                    client->get_number_physical_softkeys());
        warned = true;
    }
    sent.clear();
    configSynced = false;
    if (SystemTiming::time_expired_ms(partnerSinceMs, 10000)) forget();
}

void IsobusVt::Impl::sections(const View& v) {
    // One character a section, 16 to a line, as the implement reports them.
    std::string map = "No sections connected";
    const int n = v.status.sections < 64 ? v.status.sections : 64;
    if (n > 0) {
        map.clear();
        for (int i = 0; i < n; ++i) {
            if (i) map.push_back(i % 16 == 0 ? '\n' : ' ');
            map.push_back((v.status.actual >> i) & 1 ? '1' : '0');
        }
    }
    string(ImplementSectionMap, map);
}

// Every string here fits the length its object has in the pool; a terminal refuses a longer
// one. The layouts are upstream's.
void IsobusVt::Impl::strings(const View& v) {
    const IsobusStatus& st = v.status;
    const bool implement = st.sections > 0;
    const std::string implementName = implement ? std::string(st.implement).substr(0, 16) : "No implement";
    const char* sectionControl = st.sectionControl ? "ENABLED" : "DISABLED";
    const bool preferred = st.state == IsobusStatus::State::Claimed &&
                           st.address == isobus::preferred_addresses::IndustryGroup2::TaskController_MappingComputer;
    const std::string age = lastAppMs == 0 ? "never" : format("%u s", SystemTiming::get_time_elapsed_ms(lastAppMs) / 1000);

    string(VTWorkingSetStatusLabel, "HAT IP");
    string(VTAogIPStr, v.ip.substr(0, 15));
    string(VTWorkingSetStatusStr, !preferred ? "ADDR!" : (v.appConnected ? "OK" : "OFF"));
    string(VTSectionsFromAOGS, format("Name             %s\nSections         %u\nSection control  %s", implementName.c_str(),
                                      st.sections, sectionControl));

    const auto functions = isobus::CANNetworkManager::CANNetwork.get_control_functions(false);
    unsigned online = 0, shown = 0;
    std::string rows;
    for (const auto& cf : functions) {
        if (!cf || !cf->get_address_valid()) continue;
        ++online;
        if (shown >= 7) continue;
        const auto name = cf->get_NAME();
        const unsigned sectionCount = v.implementName && name.get_full_name() == v.implementName ? st.sections : 0;
        if (shown++) rows += '\n';
        rows += format("0x%02X  %-10u%-6u%-9u%u", cf->get_address(), name.get_function_code(), name.get_manufacturer_code(),
                       static_cast<unsigned>(name.get_identity_number()), sectionCount);
    }
    if (!shown) rows = "No control functions online";

    const std::string distance = v.distanceMm < 1000000u ? format("%.1f m", v.distanceMm / 1000.0)
                                                         : format("%.2f km", v.distanceMm / 1000000.0);
    string(VTControlFunctionsStr,
           format("Control funcs    %u\nTask state       RUNNING\nDirection        %s\nDistance         %s\nApp packet age   %s",
                  online, v.appConnected ? "FWD" : "--", distance.c_str(), age.c_str()));

    const bool tecuActive = st.tecu == IsobusStatus::Tecu::Active;
    string(ConfigHydliftLabel, "Hydlift: not impl.");
    string(ConfigNmeaReadLabel, "NMEA Read: N/A");
    string(ConfigNmeaSendLabel, tecuActive ? "NMEA Send: ON" : "NMEA Send: OFF");
    string(ConfigTecuLabel, format("TECU: %s (restart req)", tractorEcuSetting ? "ON" : "OFF"));

    string(NetworkConnectedValue, std::to_string(online).substr(0, 3));
    string(NetworkRows, rows);

    string(ImplementActiveDDOP, implementName);
    string(ImplementSectionControl, sectionControl);
    string(ImplementWorkingWidth, implement && st.widthM > 0 ? format("%.2f", st.widthM) : "n/a");
    string(ImplementBoomOffset, "n/a");
    string(ImplementSectionCount, std::to_string(st.sections));

    string(DiagnosticsValues, v.appConnected ? "ONLINE" : "OFFLINE");
    string(DiagnosticsLastPacket, age.substr(0, 9));
    string(DiagnosticsTcAddress, st.state == IsobusStatus::State::Claimed ? format("0x%02X", st.address) : "not claimed");
    string(DiagnosticsTaskState, "RUNNING");
    string(DiagnosticsActiveDDOP, implement ? implementName : "none");
    string(DiagnosticsTcClients, std::to_string(st.clients));
    const char* alarm = "No active alarms";
    if (!preferred) alarm = st.state == IsobusStatus::State::Claimed ? "TC address conflict" : "TC address not claimed";
    else if (!v.appConnected) alarm = "App not connected";
    else if (!implement) alarm = "Waiting for implement";
    string(DiagnosticsAlarmValue, alarm);
}

IsobusVt::IsobusVt(std::shared_ptr<isobus::InternalControlFunction> tc, std::function<void(bool)> setTractorEcu)
    : impl_(std::make_unique<Impl>()) {
    impl_->tc = std::move(tc);
    impl_->setTractorEcu = std::move(setTractorEcu);
}

IsobusVt::~IsobusVt() {
    if (impl_->client && impl_->started) impl_->client->terminate();
}

bool IsobusVt::update(const View& v) {
    Impl& m = *impl_;
    if (!m.client) {
        m.tractorEcuSetting = v.tractorEcuSetting;
        m.setup();
    }
    if (v.appConnected) m.lastAppMs = SystemTiming::get_timestamp_ms();
    if (!m.started) {
        // Nothing is sent until a terminal has an address.
        auto partner = m.client->get_partner_control_function();
        if (!partner || !partner->get_address_valid()) return false;
        m.client->initialize(false);  // no thread of its own: update() below drives it
        m.started = true;
        m.partnerSinceMs = SystemTiming::get_timestamp_ms();
        if (!m.everStarted) m.disconnectedSinceMs = m.partnerSinceMs;
        m.everStarted = true;
        if (partner->get_NAME().get_full_name() != m.partnerName)
            LOG_INFO(Can, "ISOBUS: terminal at address %u: offering it the status screen", partner->get_address());
        m.partnerName = partner->get_NAME().get_full_name();
        return false;
    }
    m.client->update();
    if (!m.client->get_is_connected()) {
        m.disconnected();
        return false;
    }
    m.partnerSinceMs = SystemTiming::get_timestamp_ms();
    if (!m.wasConnected) {
        m.wasConnected = true;
        m.warned = false;
    }
    if (!m.capabilitiesLogged) {
        m.capabilitiesLogged = true;
        LOG_NOTICE(Can, "ISOBUS: terminal: the status screen is on the terminal (version %u, %ux%u, soft keys %u virtual / %u physical)",
                   static_cast<unsigned>(m.client->get_connected_vt_version()), m.client->get_number_x_pixels(),
                   m.client->get_number_y_pixels(), m.client->get_number_virtual_softkeys(),
                   m.client->get_number_physical_softkeys());
        if (m.client->get_number_virtual_softkeys() < 5)
            LOG_WARNING(Can, "ISOBUS: terminal: the screen needs five soft keys and this terminal has %u",
                        m.client->get_number_virtual_softkeys());
    }
    if (!m.configSynced) {
        // What this build does not do is greyed out on the settings page.
        m.client->send_enable_disable_object(ConfigHydliftAuxN, Vt::EnableDisableObjectCommand::DisableObject);
        m.client->send_enable_disable_object(ConfigNmeaRead, Vt::EnableDisableObjectCommand::DisableObject);
        m.client->send_enable_disable_object(ConfigNmeaSend, Vt::EnableDisableObjectCommand::DisableObject);
        m.client->send_change_numeric_value(ConfigNmeaSend, v.status.tecu == IsobusStatus::Tecu::Active);
        m.client->send_change_numeric_value(ConfigTecuEnabled, m.tractorEcuSetting);
        m.configSynced = true;
    }

    // Speed in mm/s; cross-track error in mm with the pool's offset.
    const std::uint32_t speed = v.speedMmS < 0 ? static_cast<std::uint32_t>(-v.speedMmS) : static_cast<std::uint32_t>(v.speedMmS);
    m.helper->set_numeric_value(VTSpeedValue, v.appConnected ? speed : 0u);
    m.helper->set_numeric_value(VTXteValue, (v.appConnected ? static_cast<std::uint32_t>(v.xteMm) : 0u) ^ 0x80000000u);
    m.helper->set_numeric_value(ConfigTecuEnabled, m.tractorEcuSetting);

    if (SystemTiming::time_expired_ms(m.lastSectionsMs, 100)) {
        m.lastSectionsMs = SystemTiming::get_timestamp_ms();
        m.sections(v);
    }
    if (SystemTiming::time_expired_ms(m.lastStatusMs, 1000)) {
        m.lastStatusMs = SystemTiming::get_timestamp_ms();
        m.strings(v);
    }
    return true;
}

